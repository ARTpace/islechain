const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('static/index.html','utf8');
const source=fs.readFileSync('static/modules/settings.js','utf8');
const values=new Map();let writes=0,applies=0;
const context={window:{},document:{querySelector:()=>null},localStorage:{getItem:key=>values.get(key),setItem:(key,value)=>{writes++;values.set(key,value);}},Set,alerts:[]};
context.alert=message=>context.alerts.push(message);
vm.createContext(context);
vm.runInContext(html.slice(html.indexOf('        window.FeatureModules = {'),html.indexOf('        FeatureModules.ready =')),context);
const mods=context.window.FeatureModules;
mods.apply=()=>applies++;
mods.access={visitor:false,guest_disabled:['training','canvas','zimage']};
mods.setMany(['chat-gen','zimage','klein','missing'],false);
assert.equal(writes,1);assert.equal(applies,1);
assert.equal(mods.map().zimage,false);assert.equal(mods.map().klein,false);
assert.equal(mods.map()['chat-gen'],undefined);assert.equal(mods.map().missing,undefined);
mods.setMany(['zimage'],true);
assert.equal(mods.map().zimage,undefined);assert.equal(mods.map().klein,false);
const start=source.indexOf('    async applyModuleBatch(');
const end=source.indexOf('    bindLookSettings()',start);
vm.runInContext('class BatchSettings {'+source.slice(start,end)+'} window.BatchSettings=BatchSettings;',context);
const ui=new context.window.BatchSettings();ui.renderModules=async()=>{};
ui.moduleSelection=new Set(['zimage','klein','training']);
let requests=[];
context.fetch=async(url,options)=>{
    requests.push({url,data:JSON.parse(options.body)});
    return {ok:true,json:async()=>({visitor:false,guest_disabled:JSON.parse(options.body).guest_disabled})};
};
(async()=>{
    await ui.applyModuleBatch('guest-off');
    assert.equal(requests.length,1);
    assert.deepEqual([...mods.access.guest_disabled].sort(),['canvas','klein','training','zimage']);
    await ui.applyModuleBatch('guest-on');
    assert.equal(requests.length,2);
    assert.deepEqual([...mods.access.guest_disabled].sort(),['canvas','training']);
    assert.equal(ui.moduleSelection.size,3);
    const before=JSON.stringify(mods.access);
    context.fetch=async()=>({ok:false,json:async()=>({detail:'denied'})});
    await ui.applyModuleBatch('guest-off');
    assert.equal(JSON.stringify(mods.access),before);
    assert.equal(ui.moduleSaving,false);
    assert.equal(context.alerts[0],'denied');
    mods.access.visitor=true;
    await ui.applyModuleBatch('guest-off');
    assert.equal(context.alerts.length,1);
    mods.access.visitor=false;
    let release;
    context.fetch=()=>new Promise(resolve=>{release=resolve;});
    const saving=ui.applyModuleBatch('guest-off');await Promise.resolve();
    assert.equal(ui.moduleSaving,true);
    const oldWrites=writes;
    await ui.applyModuleBatch('local-off');
    assert.equal(writes,oldWrites);
    release({ok:true,json:async()=>({visitor:false,guest_disabled:['training']})});await saving;
    assert.equal(ui.moduleSaving,false);
    console.log('批量开关单次写入、锁定项保护、未选项保留、访客单次请求、失败回退与并发保护检查通过');
})().catch(error=>{console.error(error);process.exitCode=1;});
