const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('static/modules/settings.js', 'utf8');
const start = source.indexOf("        host.querySelectorAll('[data-module-drag]')");
const end = source.indexOf("        host.querySelectorAll('[data-module-toggle]')", start);
function fixture() {
    const calls = [];
    const classes = () => ({add() {}, remove() {}});
    const rows = [0, 1, 2].map((n) => ({dataset: {moduleRow: String(n)}, classList: classes(), style: {}, getBoundingClientRect: () => ({top:n*80, height:64})}));
    rows.forEach(row => row.parentElement = {querySelectorAll: () => rows});
    let captured = false;
    const handle = {dataset:{moduleDrag:'0'}, closest:()=>rows[0], setPointerCapture(){captured=true}, hasPointerCapture:()=>captured, releasePointerCapture(){captured=false}};
    const host = {querySelectorAll:()=>[handle], closest:()=>null};
    const owner = {renderModules(){ calls.push('render'); return Promise.resolve(); }};
    new Function('host','mods','groups','busy','requestAnimationFrame','cancelAnimationFrame',source.slice(start,end)).call(owner,host,{moveTo(...args){calls.push(args)}},[],false,()=>1,()=>{});
    const event = {pointerId:1,isPrimary:true,button:0,clientY:10,preventDefault(){}};
    return {handle,calls,event,rows};
}
let f=fixture();
f.handle.onpointerdown(f.event);
f.handle.onpointermove({pointerId:1,clientY:225});
assert.equal(f.rows[1].style.transform, 'translateY(-80px)');
assert.equal(f.rows[0].style.transform, 'translateY(160px)');
f.handle.onpointerup({pointerId:1,type:'pointerup'});
assert.equal(f.rows[1].style.transform, '');
assert.deepEqual(f.calls,[['0','2',true],'render']);
f=fixture();
f.handle.onpointerdown(f.event);
f.handle.onpointermove({pointerId:1,clientY:225});
f.handle.onpointercancel({pointerId:1,type:'pointercancel'});
assert.deepEqual(f.calls,[]);
assert.ok(f.rows.every(row => row.style.transform === ''));
f=fixture();
f.handle.onpointerdown(f.event);
f.handle.onpointerup({pointerId:1,type:'pointerup'});
assert.deepEqual(f.calls,[],'轻触手柄不应改变顺序');
assert.match(source,/\.module-row \{[^}]*touch-action:pan-y/);
assert.match(source,/\.module-drag \{[^}]*touch-action:none/);
const render = source.slice(source.indexOf('    async renderModules()'), source.indexOf('    async applyModuleBatch('));
assert.equal((render.match(/\+ bulk;/g)||[]).length,1,'批量栏仅出现一次');
console.log('触控拖动跨多行、取消、轻触不排序、滚动区域和单一批量栏检查通过');
