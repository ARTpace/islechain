const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({window:{},setInterval(){},Map,Set,JSON,console});
vm.runInContext(fs.readFileSync('static/js/game-model3d.js','utf8'),context);
const {canConnect,types}=context.window.GameModel3D;
const node=(type,projectId='p1')=>({id:type,type,projectId});
assert.equal(types.length,3);
assert.equal(canConnect(node('gameModelAsset'),node('gameAnimate3d')),true);
assert.equal(canConnect(node('gameModel3d'),node('gameAnimate3d')),true);
assert.equal(canConnect(node('gameAnimate3d'),node('gameDevelop')),true);
assert.equal(canConnect(node('gameModelAsset'),node('gameModel3d')),true);
assert.equal(canConnect(node('gameModelAsset'),node('gameModelAsset')),false);
assert.equal(canConnect(node('gameDevelop'),node('gameModel3d')),false);
assert.equal(canConnect({id:'i',type:'image'},node('gameModel3d')),true);
assert.equal(canConnect({id:'p',type:'prompt'},node('gameModel3d')),true);
assert.equal(canConnect({id:'o',type:'output'},node('gameModel3d')),true);
assert.equal(canConnect({id:'g',type:'generator'},node('gameModel3d')),true);
assert.equal(canConnect(node('gameModelAsset','other'),node('gameAnimate3d')),false);
assert.equal(canConnect(node('gamePlan'),node('gameDevelop')),null);
const modelProject={id:'p1',canvasId:'canvas1',mediaAssets:[{id:'asset1',revision:1,contentHash:'hash',kind:'model'}]};
context.canvas={id:'canvas1'};context.nodes=[];
let ensured=0,converted=0,written=0;
context.window.GamePipeline={project:modelProject,ensureProject:async()=>{ensured++;},workflow:async operation=>operation({project:modelProject,write:async()=>{written++;return {project:modelProject};}})};
context.window.GameModelImport={isModel:file=>/\.(obj|glb)$/i.test(file.name),convert:async file=>{converted++;return {name:file.name.replace(/\.obj$/,'.glb'),size:10};}};
context.window.GameWorkflow={addNode:async(type,point)=>{const n={id:'import'+context.nodes.length,type,projectId:'p1',...point};context.nodes.push(n);return n;}};
context.FileReader=class {readAsDataURL(){this.result='data:model/gltf-binary;base64,encoded';this.onload();}};
context.scheduleSave=()=>{};context.refreshNodes=()=>{};
const ref={...node('gameModelAsset'),modelAssetId:'asset1',modelReferenceKey:'asset1:1:hash',modelReferenceUrl:'/upload/reference.png'};
assert.equal(canConnect(ref,node('generator',undefined)),true);
assert.equal(canConnect(ref,{id:'llm',type:'llm'}),true);
assert.equal(canConnect({...ref,modelReferenceKey:'old'},node('generator')),false,'替换模型后的旧参考图不继续传给下游');
assert.equal(context.window.GameModel3D.referenceImages(ref)[0].url,'/upload/reference.png');
assert.equal(canConnect(ref,node('gamePlan','other')),false);
context.window.GamePipeline.project=null;
assert.equal(canConnect(ref,{id:'generator',type:'generator'}),true,'项目索引加载前不删除已保存的参考连线');
context.window.GamePipeline.project=modelProject;
(async()=>{
    assert.equal(await context.window.GameModel3D.dropModels([{name:'one.obj',size:10},{name:'two.glb',size:10},{name:'texture.png',size:10}],{x:10,y:20}),true);
    assert.equal(ensured,1);assert.equal(written,2);assert.equal(context.nodes.length,2);
    assert.equal(context.nodes[0].modelAssetId,'asset1');assert.equal(context.nodes[1].x,490);
    assert.equal(await context.window.GameModel3D.dropModels([{name:'texture.png',size:10}],{x:0,y:0}),false);
    assert.equal(ensured,1,'普通图片不创建项目');
    await assert.rejects(context.window.GameModel3D.dropModels([{name:'large.glb',size:257*1048576}],{x:0,y:0}),/256 MiB/);
    assert.ok(converted>=2);
    console.log('GAME_MODEL3D_OK: links, stale references, multi-model drop, companion files, batch limit');
})().catch(error=>{console.error(error);process.exitCode=1;});
