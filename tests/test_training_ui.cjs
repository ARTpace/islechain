const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const context={window:{},document:{addEventListener(){}},URL};
vm.runInNewContext(fs.readFileSync('static/modules/training.js','utf8'),context);
const ui=context.window.TrainingUI;
const generic=ui.parseConnection(JSON.stringify({mcpServers:{kohya_lora:{url:'http://127.0.0.1:19366/mcp',headers:{Authorization:'Bearer test-key'}}}}));
assert.equal(generic.token,'test-key');
const codex=ui.parseConnection('[mcp_servers.kohya_lora]\nurl = "http://127.0.0.1:19366/mcp"\nhttp_headers = { Authorization = "Bearer test-key" }\n');
assert.equal(codex.token,'test-key');
for(const text of ['bad',JSON.stringify({url:'http://evil.test/mcp',headers:{Authorization:'secret'}}),JSON.stringify({url:'http://127.0.0.1:19366/mcp',headers:{}})])assert.throws(()=>ui.parseConnection(text));
const before={mode:'character',trigger:'old',params:{rank:8,max_epochs:10}};
const after=structuredClone(before);after.params.rank=16;
assert.equal(JSON.stringify(ui.changedConfig(before,after)),JSON.stringify({params:{rank:16}}));
assert.equal(JSON.stringify(ui.changedConfig(before,{...before,params:{rank:8}})),JSON.stringify({params:{max_epochs:null}}));
assert.equal(before.params.rank,8);
const html=fs.readFileSync('static/app/training.html','utf8');
const ids=new Set([...html.matchAll(/id="([^"]+)"/g)].map(match=>match[1]));
const script=fs.readFileSync('static/modules/training.js','utf8');
for(const match of script.matchAll(/\$\('([^']+)'\)/g))assert.ok(ids.has(match[1]),'missing UI element: '+match[1]);
assert.match(script,/expected_revision:revision/);
assert.match(script,/after:offset,limit:200/);
assert.match(script,/confirmed:true/);
assert.match(script,/\.textContent=/);
assert.doesNotMatch(script,/innerHTML\s*=/,'trainer output must not become HTML');
assert.match(fs.readFileSync('static/index.html','utf8'),/id="frame-training"/);
console.log('训练界面：连接配置解析、增量保存、DOM 接线、日志分页与确认控制通过');
