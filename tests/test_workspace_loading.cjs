const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
function classes(initial=[]){const items=new Set(initial);return {add:x=>items.add(x),remove:x=>items.delete(x),toggle(x,on){on?items.add(x):items.delete(x);},contains:x=>items.has(x)};}
const shell={classList:classes(['is-visible'])};
const stage={setAttribute(k,v){this[k]=v;}};
const events={};
const window={addEventListener(k,fn){events[k]=fn;}};
const location={href:'http://local/static/index.html',origin:'http://local'};
vm.runInNewContext(fs.readFileSync('static/js/workspace-loading.js','utf8'),{window,location,URL,WeakMap,document:{querySelector:()=>stage,getElementById:()=>shell}});
function frame(src){return {src:null,dataset:{src},classList:classes(),contentWindow:{location:{href:'about:blank'}},getAttribute(){return this.src;},addEventListener(k,fn){this[k]=fn;}};}
const a=frame('/a'),b=frame('/b');
window.WorkspaceLoading.activate(a);
assert.equal(a.src,null,'loader must not navigate or bypass permission checks');
assert(a.classList.contains('workspace-waiting'));
a.src='/a';a.load();
assert(shell.classList.contains('is-visible'),'ignore the initial about:blank load');
a.contentWindow.location.href='http://local/a';
events.message({origin:'http://other',source:a.contentWindow,data:{type:'studio-page-ready'}});
assert(shell.classList.contains('is-visible'),'reject foreign origins');
events.message({origin:location.origin,source:b.contentWindow,data:{type:'studio-page-ready'}});
assert(shell.classList.contains('is-visible'),'reject unrelated frames');
events.message({origin:location.origin,source:a.contentWindow,data:{type:'studio-page-ready'}});
assert(!shell.classList.contains('is-visible'),'show the page at DOM readiness without waiting for load');
assert.equal(stage['aria-busy'],'false');
window.WorkspaceLoading.activate(b);b.src='/b';
assert(shell.classList.contains('is-visible'));
a.load();assert(shell.classList.contains('is-visible'),'late previous-frame load must not clear current loading');
b.contentWindow.location.href='http://local/b';b.load();
assert(!shell.classList.contains('is-visible'),'load is the fallback for pages without readiness signals');
window.WorkspaceLoading.activate(a);
assert(!shell.classList.contains('is-visible'),'cached pages do not replay the loader');
window.WorkspaceLoading.forget(a);a.src=null;
window.WorkspaceLoading.activate(a);
assert(shell.classList.contains('is-visible'),'evicted pages must load again');
a.src='/new';a.dataset.src='/new';window.WorkspaceLoading.activate(a);
events.message({origin:location.origin,source:a.contentWindow,data:{type:'studio-page-ready'}});
assert(shell.classList.contains('is-visible'),'ignore old document readiness during navigation');
a.contentWindow.location.href='http://local/login';a.load();
assert(!shell.classList.contains('is-visible'),'a completed redirect must remain visible');
window.WorkspaceLoading.activate(null);
assert(!shell.classList.contains('is-visible'),'do not cover permission errors or an empty feature list');
console.log('Workspace loading: early readiness, origin/source guards, cached/evicted navigation and permission fallback passed');
