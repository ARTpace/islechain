const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'static/modules/gallery/prompt-panel.js'), 'utf8');
const start = source.indexOf('    function buildMetaDict(');
const end = source.indexOf('    /** 构建 tags', start);
const context = vm.createContext({});
vm.runInContext(source.slice(start, end), context);
const normalize = context.buildMetaDict;
const moss = normalize({model:'ZIMAGE', type:'zimage'}, {workflow:'text2image/moss-image-sft.json', engine:'local', seed:0, width:2048, height:2048, cfg:0, cfg_scale:4});
assert.equal(moss.fields['模型'], 'moss-image-sft');
assert.equal(moss.fields['来源'], '本地 ComfyUI');
assert.equal(moss.fields['生成模式'], '文生图');
assert.equal(moss.fields['尺寸'], '2048 × 2048');
assert.equal(moss.fields['种子'], 0);
assert.equal(moss.fields['引导系数'], 0);
assert.equal(Object.keys(moss.additional).length, 0);
const cloud = normalize({}, {model_name:'new-api-model', engine:'cloud', mode:'img2img', size:'1024x1024', provider:'Example', sampler_name:'euler', custom_parameter:5});
assert.equal(cloud.fields['生成模式'], '图生图');
assert.equal(cloud.fields['服务商'], 'Example');
assert.equal(cloud.fields['采样器'], 'euler');
assert.equal(cloud.additional.custom_parameter, 5);
assert.deepEqual(Object.keys(moss.fields).slice(0,4), Object.keys(cloud.fields).slice(0,4));
assert.equal(normalize({}, {}, {}).fields['模型'], '未记录');
assert.equal(normalize({}, {generation_time_ms:12345}, {}).fields['生成时长'], '12.3 秒（含排队）');
assert.equal(normalize({}, {generation_time_ms:0}, {}).fields['生成时长'], '0.0 秒（含排队）');
assert.equal(normalize({}, {耗时:'25 秒'}, {}).fields['生成时长'], '25 秒');
assert.equal(normalize({}, {}, {}).fields['生成时长'], '未记录');
const bundle = fs.readFileSync(path.join(root, 'static/modules/gallery/bundle.js'), 'utf8');
assert.ok(bundle.includes(source.trim()), '发布包必须同步共用面板实现');
new vm.Script(bundle);
console.log('信息面板：本地/API/模式别名、零值、去重、未知参数和发布包同步检查通过');
