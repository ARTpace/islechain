const vm = require('node:vm'), fs = require('node:fs'), assert = require('node:assert/strict');
const context = vm.createContext({window: {}, escapeHtml: value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')});
vm.runInContext(fs.readFileSync('static/js/game-authoring.js', 'utf8'), context);
const api = context.window.GameAuthoring;
const table = api.fromDelimited('编号,说明\r\n001,"第一行\n第二行"\r\n002,"带""引号"""', ',', {id: 'items', title: '道具', revision: 1});
assert.equal(table.rows[0].cells.col_0, '001', '保留前导零');
assert.equal(table.rows[0].cells.col_1, '第一行\n第二行');
assert.equal(table.rows[1].cells.col_1, '带"引号"');
assert.equal(JSON.stringify(api.fromDelimited(api.csv(table), ',', table)), JSON.stringify(table), 'CSV 往返保留正文');
assert.throws(() => api.parseDelimited('a,"unterminated'), /引号/);
assert.throws(() => api.fromDelimited('a\n1,2', ',', table), /列数/);
assert.equal(api.typed('15.5', {type: 'number'}), 15.5);
assert.equal(api.typed('false', {type: 'boolean'}), false);
assert.equal(api.typed('', {type: 'number'}), null);
assert.throws(() => api.typed('NaN', {type: 'number'}), /数字/);
assert.throws(() => api.typed('yes', {type: 'boolean'}), /布尔/);
const html = api.markdown('# 标题\n**正文**\n- 条目\n![图](/output/alice/a.png)\n<script>alert(1)</script>\n[危险](javascript:alert(1))');
assert.ok(html.includes('<h1>标题</h1>') && html.includes('<strong>正文</strong>') && html.includes('<li>条目</li>'));
assert.ok(html.includes('<img src="/output/alice/a.png"'));
assert.ok(!html.includes('<script>') && !html.includes('href="javascript:'));
assert.ok(api.markdown('```\n<img onerror=x>\n```').includes('&lt;img onerror=x&gt;'));
console.log('GAME_AUTHORING_OK');
